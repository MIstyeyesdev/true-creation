        }

        /// <summary>Every Pal species' work suitability ranks and base craft speed, the offline fallback for ranking workers.</summary>
        /// <summary>Every buildable building: name, build icon and Pal requirement, for the Assignment Board rows.</summary>
        public static string Buildings(GameData data)
        {
            var sb = new StringBuilder();
            sb.AppendLine("-- pm_data_buildings.lua : every building's name, icon and Pal requirement (DT_BuildObjectIconDataTable + DT_MapObjectAssignData).");
            sb.AppendLine("-- GENERATED by PalItemgen.");
            sb.AppendLine("return {");
            foreach (var b in data.Buildings.Where(b => !string.IsNullOrEmpty(b.MapObjectId)).OrderBy(b => b.MapObjectId, StringComparer.Ordinal))
            {
                var a = b.Assignments.FirstOrDefault(x => x.WorkSuitability != "Anyone") ?? b.Assignments.FirstOrDefault();
                var suit = a?.WorkSuitability ?? "None";
                var icon = b.Icon ?? (data.Icons.TryGetValue(b.MapObjectId, out var ic) ? ic.Path : "");
                sb.Append("  ").Append(Key(b.MapObjectId)).Append(" = { name = ").Append(Q(string.IsNullOrEmpty(b.Name) ? b.MapObjectId : b.Name))
                  .Append(", icon = ").Append(Q(icon ?? ""))
                  .Append(", suitability = ").Append(Q(suit))
                  .Append(", rank = ").Append((a?.WorkSuitabilityRank ?? 1).ToString(CultureInfo.InvariantCulture))
                  .Append(", workerMax = ").Append((a?.WorkerMaxNum ?? 0).ToString(CultureInfo.InvariantCulture))
                  .AppendLine(" },");
            }
            sb.AppendLine("}");
            return sb.ToString();
        }

        public static string Pals(GameData data)
        {
            var sb = new StringBuilder();
            sb.AppendLine("-- pm_data_pals.lua : work suitability ranks per Pal species (from DT_PalMonsterParameter).");
            sb.AppendLine("-- GENERATED by PalItemgen.");
            sb.AppendLine("return {");
            foreach (var p in data.Pals.OrderBy(p => p.Id, StringComparer.Ordinal))
            {
                sb.Append("  ").Append(Key(p.Id)).Append(" = { name = ").Append(Q(p.Name ?? ""))
                  .Append(", craft = ").Append(p.CraftSpeed.ToString(CultureInfo.InvariantCulture))
                  .Append(", ranks = {");
                foreach (var kv in p.Ranks.OrderBy(k => k.Key, StringComparer.Ordinal))
                    sb.Append(' ').Append(Key(kv.Key)).Append(" = ").Append(kv.Value.ToString(CultureInfo.InvariantCulture)).Append(',');
                sb.AppendLine(" } },");
            }
            sb.AppendLine("}");
            return sb.ToString();
        }
