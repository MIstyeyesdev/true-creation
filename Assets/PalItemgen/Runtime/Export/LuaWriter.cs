        }

        /// <summary>Item icon texture paths (DT_ItemIconDataTable) for the menu's search list.</summary>
        public static string Icons(GameData data)
        {
            var sb = new StringBuilder();
            sb.AppendLine("-- pm_data_icons.lua : item id -> icon texture path (from DT_ItemIconDataTable).");
            sb.AppendLine("-- GENERATED by PalItemgen.");
            sb.AppendLine("return {");
            foreach (var i in data.Items.Where(i => !string.IsNullOrEmpty(i.Icon)).OrderBy(i => i.Id, StringComparer.Ordinal))
                sb.Append("  ").Append(Key(i.Id)).Append(" = ").Append(Q(i.Icon)).AppendLine(",");
